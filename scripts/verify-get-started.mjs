import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const csv = 'latitude,longitude,acq_date,acq_time,instrument,satellite,confidence,frp\n9.4,-0.84,2026-11-12,1325,VIIRS,N,n,12.5\n';
await page.route('**/api/fires/latest', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ products: [{ product: 'VIIRS_SNPP_NRT', csv }], from: '2026-11-10', to: '2026-11-12', fetchedAt: '2026-11-12T12:00:00Z' }) }));
const queries = [];
await page.route('https://api.gdeltproject.org/**', route => {
  const query = new URL(route.request().url()).searchParams.get('query');
  queries.push(query);
  return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ articles: [{ title: `Test fixture: ${query.includes('drought') ? 'drought' : 'fire'} coverage`, url: 'https://example.org/story', seendate: '20261112T120000Z' }] }) });
});
await page.goto('http://127.0.0.1:5173');
await page.getByRole('heading', { name: 'Choose your observation window' }).waitFor();
if ((await page.locator('.observation-total').innerText()).includes('0')) throw new Error('Unloaded data presented as zero');
await page.getByRole('button', { name: 'Load latest NASA data', exact: true }).click();
await page.getByText('NASA API observations', { exact: true }).waitFor();
await page.getByText(/Loaded 1 NASA detections/).waitFor();
if (await page.locator('.observation-total').innerText() !== '1\ndetection records') throw new Error('Map count did not update');
if (await page.getByLabel('From', { exact: true }).inputValue() !== '2026-11-10') throw new Error('Old date filters not reset');
await page.screenshot({ path: 'test-results/start-desktop.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'test-results/start-mobile.png' });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Explorer mobile overflow');
await page.getByRole('button', { name: 'News updates', exact: true }).click();
await page.getByRole('link', { name: 'Test fixture: fire coverage' }).waitFor();
await page.getByLabel('Search Ghana news', { exact: true }).fill('drought');
await page.getByRole('button', { name: 'Search news', exact: true }).click();
await page.getByRole('link', { name: 'Test fixture: drought coverage' }).waitFor();
if (!queries.at(-1).includes('Ghana "drought"')) throw new Error('Search terms not sent');
await page.screenshot({ path: 'test-results/search-mobile.png' });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('News mobile overflow');
await page.setViewportSize({ width: 1440, height: 1000 });
await page.screenshot({ path: 'test-results/search-desktop.png' });
await page.getByRole('button', { name: 'Fire explorer', exact: true }).click();
await page.getByText('NASA API observations', { exact: true }).waitFor();
if (errors.length) throw new Error(errors.join('\n'));
console.log('Start/search flow passed using test fixtures: live-load action updates map/counts/dates, visible search sends keywords, navigation preserves data, desktop/mobile fit.');
await browser.close();
