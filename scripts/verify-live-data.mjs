import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('requestfailed', req => { if (req.url().includes('api.gdeltproject.org')) console.log('GDELT network:', req.failure()?.errorText); });
page.on('response', response => { if (response.url().includes('api.gdeltproject.org')) console.log('GDELT HTTP:', response.status()); });
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button', { name: 'Load latest NASA data', exact: true }).click();
await page.getByText('NASA API observations', { exact: true }).waitFor({ timeout: 45000 });
console.log('Live NASA UI:', await page.locator('.observation-total').innerText());
await page.screenshot({ path: 'test-results/live-start-desktop.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'test-results/live-start-mobile.png' });
await page.getByRole('button', { name: 'News updates', exact: true }).click();
await page.getByRole('button', { name: 'Check updates', exact: true }).waitFor({ timeout: 35000 });
console.log('Live news UI:', await page.locator('.news-status').innerText(), 'headlines:', await page.locator('.news-list li').count());
await page.screenshot({ path: 'test-results/live-news-mobile.png' });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.screenshot({ path: 'test-results/live-news-desktop.png' });
if ((await page.locator('.news-status').innerText()).includes('Could not reach')) process.exitCode = 1;
await browser.close();
