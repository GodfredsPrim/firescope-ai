  await page.getByText('Harmonization confidence: not established', { exact: true }).click();
  await page.getByText('Enter polygon coordinates with the keyboard', { exact: true }).click();
  await page.getByLabel('Vertices as JSON').fill(JSON.stringify(polygon));
