  await page.locator('.roi-weather>summary').click();
  await page.getByLabel('Vertices as JSON').fill('[[0,0],[1,1],[0,1],[1,0]]');
  await page.getByRole('button', { name: 'Apply polygon', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('edges must not cross');
