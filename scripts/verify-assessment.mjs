  await page.goto(`${base}/#assessment`);
  await expect(page.getByRole('heading', { name: 'Area of interest', exact: true })).toBeVisible();
  await expect(page.locator('.dataset-badge')).toContainText('Historical NASA snapshot', { timeout: 30000 });
