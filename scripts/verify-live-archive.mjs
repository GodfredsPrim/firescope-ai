import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const url = new URL('http://127.0.0.1:5173/api/fires/search');
url.search = new URLSearchParams({ from: '2025-01-01', to: '2025-01-03', mode: 'archive', bounds: '-3.3,4.5,1.3,11.2' }).toString();
const response = await fetch(url, { signal: AbortSignal.timeout(75000) });
const body = await response.json();
if (!response.ok) throw new Error(body.error);
const folder = 'artifacts/nasa-ghana-2025-01-01_03';
await mkdir(folder, { recursive: true });
for (const product of body.products) await writeFile(`${folder}/${product.product}.csv`, product.csv);
await writeFile(`${folder}/provenance.json`, JSON.stringify({ provider: 'NASA FIRMS', access: 'Authenticated API retrieval; key omitted', from: body.from, to: body.to, bounds: body.bounds, fetchedAt: body.fetchedAt, products: body.products.map(p => ({ name: p.product, rows: p.csv.trim().split(/\r?\n/).length - 1 })), purpose: 'Observational demonstration dataset; not independently labeled validation reference data.' }, null, 2));
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button', { name: /Explore historical NASA data/ }).click();
await page.getByText('NASA API observations', { exact: true }).waitFor({ timeout: 80000 });
console.log('Real archive UI:', await page.locator('.observation-total').innerText());
await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].some(img => img.complete && img.naturalWidth > 0), undefined, { timeout: 15000 }).catch(() => {});
await page.screenshot({ path: 'test-results/real-archive-explorer.png' });
await page.getByRole('button', { name: 'Sensor comparison', exact: true }).click();
await page.getByRole('heading', { name: 'Cross-sensor observation linking' }).waitFor();
console.log('Real archive analysis [pairs, unpaired MODIS, unpaired VIIRS, groups]:', await page.locator('.link-metrics dd').allTextContents());
await page.locator('.link-analysis').screenshot({ path: 'test-results/real-archive-linking.png' });
if (errors.length) throw new Error(errors.join('\n'));
console.log('Real two-sensor archive workflow passed. Original NASA CSVs and a key-free provenance manifest saved in', folder);
await browser.close();
