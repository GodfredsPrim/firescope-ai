import { chromium } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
const header = 'latitude,longitude,acq_date,acq_time,instrument,satellite,confidence,frp,scan,track,version,daynight\n';
const modis = header + '9.4,-0.84,2025-01-01,1200,MODIS,T,80,12,1,1,6.1,D\n9.9,-0.84,2025-01-01,1300,MODIS,T,80,14,1,1,6.1,D';
const viirs = header + '9.401,-0.84,2025-01-01,1210,VIIRS,N,n,8,0.4,0.4,2.0,D\n9.901,-0.84,2025-01-01,1310,VIIRS,N,n,9,0.4,0.4,2.0,D\n9.2,-0.84,2025-01-02,1200,VIIRS,N,n,7,0.4,0.4,2.0,D';
let requested;
await page.route('**/api/fires/**', route => {
  requested = new URL(route.request().url());
  return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ from: '2025-01-01', to: '2025-01-03', mode: 'archive', bounds: [-3.3, 4.5, 1.3, 11.2], fetchedAt: '2026-11-12T12:00:00Z', products: [{ product: 'MODIS_SP', csv: modis }, { product: 'VIIRS_SNPP_SP', csv: viirs }] }) });
});
await page.goto('http://127.0.0.1:5173');
await page.getByRole('heading', { name: 'Choose your observation window' }).waitFor();
await page.screenshot({ path: 'test-results/science-empty-desktop.png' });
await page.getByText('Search an area and date range', { exact: false }).click();
await page.getByLabel('From (UTC)', { exact: true }).fill('2025-01-01');
await page.getByLabel('To (UTC)', { exact: true }).fill('2025-01-31');
await page.getByRole('button', { name: 'Search NASA observations' }).click();
await page.getByRole('alert').filter({ hasText: 'Choose 1-10 days' }).waitFor();
if (requested) throw new Error('Invalid interval made a request');
await page.getByLabel('To (UTC)', { exact: true }).fill('2025-01-03');
await page.getByLabel('NASA product', { exact: true }).selectOption('archive');
await page.getByRole('button', { name: 'Search NASA observations' }).click();
await page.getByText('NASA API observations', { exact: true }).waitFor();
if (requested.searchParams.get('mode') !== 'archive' || requested.searchParams.get('from') !== '2025-01-01') throw new Error('Archive query not sent');
if (await page.locator('.observation-total').innerText() !== '5\ndetection records') throw new Error('Wrong observation count');
await page.locator('.data-request details').evaluate(element => element.open = false);
await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].some(img => img.complete && img.naturalWidth > 0), undefined, { timeout: 15000 }).catch(() => {});
await page.screenshot({ path: 'test-results/science-explorer-desktop.png' });
await page.getByLabel('Calendar measure').selectOption('groups');
await page.getByLabel('2025-01-01, 2 linked groups; coverage unknown', { exact: true }).waitFor();
await page.getByLabel('2025-01-02, 1 linked groups; coverage unknown', { exact: true }).waitFor();
let downloadEvent = page.waitForEvent('download');
await page.getByRole('button', { name: 'Export daily calendar' }).click();
let download = await downloadEvent;
const csv = await readFile(await download.path(), 'utf8');
if (!csv.includes('candidate_pairs') || !csv.includes('2025-01-01,2,2,2,2')) throw new Error('Wrong activity export');
await page.locator('.calendar-panel').screenshot({ path: 'test-results/science-calendar-desktop.png' });
await page.getByRole('button', { name: 'Sensor comparison', exact: true }).click();
await page.getByRole('heading', { name: 'Cross-sensor observation linking' }).waitFor();
const values = await page.locator('.link-metrics dd').allTextContents();
if (JSON.stringify(values) !== JSON.stringify(['2', '0', '1', '3'])) throw new Error(`Wrong match metrics: ${values}`);
downloadEvent = page.waitForEvent('download');
await page.getByRole('button', { name: 'Export analysis evidence' }).click();
download = await downloadEvent;
const report = JSON.parse(await readFile(await download.path(), 'utf8'));
if (report.candidate_pairs !== 2 || report.candidate_links.length !== 2 || !report.limitations.length) throw new Error('Incomplete evidence export');
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'test-results/science-comparison-desktop.png' });
await page.locator('.link-analysis').screenshot({ path: 'test-results/science-link-panel-desktop.png' });
await page.setViewportSize({ width: 390, height: 844 });
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'test-results/science-comparison-mobile.png' });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Comparison mobile overflow');
await page.getByRole('button', { name: 'Fire explorer', exact: true }).click();
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'test-results/science-explorer-mobile.png' });
await page.locator('.calendar-panel').screenshot({ path: 'test-results/science-calendar-mobile.png' });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Explorer mobile overflow');
await page.setViewportSize({ width: 320, height: 740 });
await page.evaluate(() => window.scrollTo(0, 0));
await page.screenshot({ path: 'test-results/science-navigation-320.png' });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('320px navigation overflow');
const iconWidths = await page.locator('.nav-item svg').evaluateAll(icons => icons.map(icon => icon.getBoundingClientRect().width));
if (iconWidths.some(width => width < 17)) throw new Error('Mobile navigation icons collapsed');
await page.getByRole('button', { name: 'Method & limitations', exact: true }).click();
await page.getByRole('heading', { name: 'Before claiming validated harmonization' }).waitFor();
if (errors.length) throw new Error(errors.join('\n'));
console.log('Science workflow passed with labeled test fixtures: bounded archive search, both sensors, two correct candidate pairs, linked calendar, daily CSV and evidence JSON, method disclosures, desktop/mobile, no browser errors.');
await browser.close();
